const assert=require('node:assert/strict');
const {TYPES,ports,fits,canConnect,validate,parse}=require('./dist/model.js');
const c=(id,type,row,slot)=>({id,type,row,slot,label:id,rating:TYPES[type].rating,on:true});
const s={version:1,name:'Test',components:[c('q','MAIN',0,0),c('r','RCD',1,0),c('n','N',0,10),c('p','PE',0,14)],wires:[],circuits:[]};
assert.equal(fits(s,c('new','MCB',0,0),0,3),false,'collision');
assert.equal(fits(s,c('new','MCB',0,0),0,4),true,'adjacent available');
assert.equal(fits(s,c('new','RCD',0,0),0,16),false,'outside rail');
assert.equal(fits(s,s.components[0],0,0),true,'own slot allowed');
assert.equal(canConnect(s,{device:'q',port:'b0'},{device:'r',port:'t0'}),null);
assert.notEqual(canConnect(s,{device:'q',port:'b0'},{device:'q',port:'t0'}),null);
assert.notEqual(canConnect(s,{device:'q',port:'no'},{device:'r',port:'t0'}),null);
s.wires.push({id:'w',a:{device:'q',port:'b0'},b:{device:'r',port:'t0'},role:'L1',gauge:6});
assert.notEqual(canConnect(s,s.wires[0].b,s.wires[0].a),null,'duplicate reversed');
assert.equal(validate(s).filter(x=>x.severity==='error').length,0,'same phase');
s.wires[0].b.port='t1';
assert.ok(validate(s).some(x=>x.title==='Połączono różne fazy'));
s.wires[0].b={device:'n',port:'t0'};
assert.ok(validate(s).some(x=>x.title==='Różne funkcje zacisków'));
assert.deepEqual(parse(s),s);
assert.throws(()=>parse({...s,components:[...s.components,c('bad','MAIN',0,1)]}),/zachodzą/);
assert.throws(()=>parse({...s,wires:[{...s.wires[0],gauge:99}]}),/połączenie/);
assert.throws(()=>parse({...s,components:[c('"','MCB',0,7)]}),/aparat/);
assert.throws(()=>parse({version:1}),/format/);
assert.equal(ports(c('spd','SPD',0,0)).filter(p=>p.side==='b')[0].role,'PE');
assert.throws(()=>parse({...s,circuits:[{id:'bad"',name:'x',device:'',power:1,cable:'x'}]}),/obwód/);
assert.throws(()=>parse({...s,circuits:[{id:'x',name:'x',device:'',power:1,cable:'x'},{id:'x',name:'y',device:'',power:1,cable:'x'}]}),/obwód/);
assert.throws(()=>parse({...s,wires:[{...s.wires[0],id:'bad"'}]}),/połączenie/);
const freeInfo=validate({version:1,name:'T',components:[c('m','MCB',3,0)],wires:[],circuits:[]});
assert.ok(freeInfo.length===1&&freeInfo[0].severity==='info','free terminals are informational, not warnings');
assert.equal(validate(s).filter(x=>x.severity==='warn').length,0,'free terminals never raise warnings');
console.log('21 model checks passed: collisions, terminal references, duplicates, phase/function conflicts, import schema, SPD port model.');
